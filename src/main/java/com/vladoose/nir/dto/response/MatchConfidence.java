package com.vladoose.nir.dto.response;

/**
 * Зона честности матча. Считается из РЕЗУЛЬТАТА, а не из запроса — прежний {@code distinctive}
 * мерил число токенов и на практике был инвертирован: «Бокс микробиологической безопасности»
 * (3 токена, 57 кандидатов) показывал проценты уверенно, а однословные лоты скромничали.
 *
 * <p><b>Из результата — это ТРИ входа, а не один</b> (калибровка 2026-08-02, см.
 * {@code RegistryMatchService}): скор топ-кандидата решает только «показывать ли процент»;
 * сколько в реестре РАВНОПРАВНЫХ ответов ({@code rivals}) и по всему ли имени лота шёл отбор
 * решают, есть ли вообще что показывать. Версия, читавшая только скор, объявляла уверенность
 * на «Перчатках» (147 равноправных записей) и на обрывке запроса.
 *
 * <p>⚠️ Здесь ранее стоял пример «Спектрофотометр (1 токен, 3 кандидата, определим)».
 * <b>Посылка неверна:</b> спектрофотометров в реестре НЦЭЛС ноль, а все три кандидата —
 * масс-спектрометры MALDI-TOF, то есть ложные срабатывания. Честный ответ для этого лота —
 * {@code CANNOT}, и сейчас он его и получает; калибровать в сторону {@code CONFIDENT} на нём
 * нельзя (разметка golden-набора: NONE).
 */
public enum MatchConfidence {
    /** Данных хватило: показываем процент и топ-кандидата. */
    CONFIDENT,
    /** Кандидаты есть, но неразличимы (генерик вроде «Перчатки»): список без процентов. */
    SHORTLIST,
    /** Определить нельзя: список свёрнут, показываем причину. */
    CANNOT
}
