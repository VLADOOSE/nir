package com.vladoose.nir.dto.response;

/** Почему матч оказался в зоне CANNOT — для честного сообщения оператору. */
public enum CannotReason {
    /** Отбор не дал ни одной записи. */
    NO_CANDIDATES,
    /** Скор низкий и техспека не разбиралась — есть что дозагрузить. */
    NEED_TECH_SPEC,
    /** Скор низкий, техспеку пытались взять и не смогли (нет файла / нечитаемый PDF / площадка недоступна). */
    TECH_SPEC_FAILED,
    /** Скор низкий, техспека разобрана — в реестре, похоже, нет подходящего. */
    WEAK_MATCH,
    /**
     * Слов лота нет в реестре: отбор шёл по ОБРЫВКУ названия, потому что остальные слова не
     * встречаются в реестре ни разу (df=0 и потому выброшены из запроса). Замер 2026-08-02 по
     * всем 1485 различным именам лотов: у 31 % лотов отбор идёт по подмножеству имени, а 2.8 %
     * отбираются по ОДНОМУ уцелевшему слову — и прежний {@code confidenceOf}, читавший только
     * верхний скор, этого не видел вовсе. Живой пример: «Криптовалютный майнер квантовый»
     * терял два слова из трёх и уверенно отвечался «Аппаратом квантовой терапии "Витязь"».
     */
    QUERY_NOT_IN_REGISTRY
}
