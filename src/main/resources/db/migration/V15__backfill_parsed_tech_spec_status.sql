-- V15: пометить УЖЕ разобранные техспеки как разобранные (tech_spec_status = 'OK').
--
-- Зачем. Переимпорт тендера обновляет required_spec описанием с площадки и щадит только лоты
-- с отметкой 'OK'. Отметку ставит TechSpecWriter, но он научился этому лишь сейчас, поэтому у
-- всех исторически разобранных лотов статус пуст — и первый же переимпорт затёр бы многотысячную
-- техспеку однострочным description_ru. Замерено на живой БД прогоном следующего импорта:
-- строки лотов выживали все (1305/1305), а разобранные ТЗ терялись все (0 из 11 уцелевших).
--
-- Критерий. Разобранное ТЗ отличается от описания площадки и длиной, и формой: извлекается оно
-- начиная с маркера раздела («Приложение 2 … Техническая спецификация»). На живой БД условия
-- совпадают ровно: длиннее 400 символов — 11 строк, и все 11 содержат маркер; строк длиннее 400
-- без маркера нет вовсе, а самые длинные описания площадки (услуги охраны, ИТ-работы) не
-- дотягивают и до 300. Оба условия оставлены вместе намеренно: длина одна отсекает не всё,
-- маркер один может не совпасть на будущих формах ТЗ.
UPDATE tender_lot
   SET tech_spec_status = 'OK'
 WHERE tech_spec_status IS NULL
   AND required_spec IS NOT NULL
   AND length(required_spec) > 400
   AND required_spec ~* 'приложение|техническ(ая|ой) специфик';
