-- Калибровка сверки «наша продукция» на наборе настоящих ТЗ (задача 6 плана 2026-10-19-product-watch, 2026-10-20).
-- Общие сокращения и чужой бренд давали «★ назван наш товар» чужим изделиям:
--   «ЭХВЧ» — аппарат электрохирургический высокочастотный любого производителя (ТЗ на BOWA ARC 303 — 17828560-1);
--   «ОБН», «ОБП», «ОБПЕ» — облучатель бактерицидный настенный / потолочный (ОБН 2×30 другого завода — 17822670-1);
--   «Valleylab» — бренд Covidien; у нас «кабель с разъёмом типа Valleylab» (ручка-чехол Valleylab — 17714835-1).
-- Модели с цифрами («ЭХВЧ-350-03», «ОБПЕ-450») остаются «назван наш товар» по кодам из названий каталога.
-- Правленые оператором группы (updated_at задан) не трогаем.
UPDATE product_group
SET search_words = '["фотек","fotek","аксион","эмалед","митар","актитон","actiton"]'
WHERE market = 'KZ' AND name = 'Наши бренды и модели (части и принадлежности)' AND updated_at IS NULL;

UPDATE product_group
SET search_words = '["электрохирургический","электрокоагулятор","коагулятор","эхвч"]',
    brand_words  = '["фотек","onyx","термошов"]'
WHERE market = 'KZ' AND name = 'Электрохирургия (Фотек)' AND updated_at IS NULL;

UPDATE product_group
