UPDATE tender_lot_result r SET protocol_reparse = TRUE
FROM tender_lot l
WHERE l.id = r.tender_lot_id
  AND r.protocol_url IS NOT NULL
  AND r.protocol_status IN ('PARSED', 'UNKNOWN_FORMAT')
  AND btrim(l.source_lot_code) ~ '-ОК[0-9]*$';
