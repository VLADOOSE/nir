-- V16: вторая половина бэкфилла статуса техспеки — поставить в очередь уже импортированные лоты.
--
-- Зачем. V14 завела колонку, и статус PENDING проставляется только НОВЫМ лотам в импорт-райтерах.
-- V15 пометила OK одиннадцать лотов, у которых ТЗ уже разобрано вручную кнопкой «ТЗ». Остальные
-- исторические лоты остались с NULL — очередь их никогда бы не взяла, и главная цель захода
-- («ТЗ разобрано у 11 лотов из 1344») не была бы достигнута ни через сутки, ни через год.
--
-- Критерий импортности — source_ext_id IS NOT NULL, а НЕ platform IS NOT NULL. Колонка platform
-- появилась только в V11 (2026-07-11), поэтому у 1119 лотов более раннего goszakup-импорта она
-- пуста: по platform в очередь попали бы 224 лота вместо 1333 (замерено на живой БД). Ручные
-- тендеры остаются с NULL осознанно — техспеку им скачивать неоткуда.
--
-- Объём осознан: ~1300 лотов встают в очередь разом. При batch-size 10 и интервале 10 минут это
-- примерно сутки капельного разбора — приемлемо для разового наполнения; троттлинг между лотами
-- защищает площадку от долбёжки.
UPDATE tender_lot l
   SET tech_spec_status = 'PENDING'
 WHERE l.tech_spec_status IS NULL
   AND EXISTS (SELECT 1 FROM tender t
                WHERE t.id = l.tender_id
                  AND t.source_ext_id IS NOT NULL);

-- Индекс под реальный запрос воркера. Прежний (V14) индексировал сам статус, а ключ у всех строк
-- очереди одинаков ('PENDING') — ORDER BY id ... LIMIT всё равно уходил в heap fetch + sort.
-- Частичный индекс ПО id отдаёт и фильтр, и порядок, и LIMIT из одного прохода.
-- IF EXISTS / IF NOT EXISTS — конвенция миграций проекта (V4, V5, V6, V13): на проде автодеплой,
-- и неидемпотентная миграция роняет старт приложения.
DROP INDEX IF EXISTS idx_lot_tech_spec_status;
CREATE INDEX IF NOT EXISTS idx_lot_tech_spec_pending ON tender_lot (id)
    WHERE tech_spec_status = 'PENDING';
